# Ввести з клавіатури норматив підтягувань.
# Створити список із значеннями підтягувань 12 випадкових учнів у діапазоні:
# 		від (норматив – 5) до (норматив + 4).
# Якщо значення менше за норматив, замінити його на –1 (норматив не виконано).
# Вивести отриманий список на екран.
import random

# Вводимо норматив
norm = int(input('Введіть норматив підтягувань: '))

# Створюємо порожній список
results = []

for i in range(12):
    # Додаємо випадкове значення до списку
    results.append(random.randint(norm - 5, norm + 4))
    
    # Перевіряємо виконання нормативу
    if results[i] < norm:
        results[i] = -1

# Виводимо результат
print(results)