# 12.2. Опис програми зміни значення даних списку
import random
# задаємо контрольне значення особистого рекорду
personal_record = int(input('Введіть значення особистого рекорду: '))

#Створюємо порожній список спроб
attempt_list = []

for i in range (10):
    # додаємо введені елементи до списку в області виконання проєкту
    attempt_list.append(random.randint((personal_record - 10), 194))
    # змінюємо елементи списку
    if attempt_list[i] > personal_record:
        attempt_list[i] = 0
# виводимо результат
print(attempt_list)



