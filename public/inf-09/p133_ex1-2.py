# Імпортуємо бібліотеку tkinter для створення графічного інтерфейсу
import tkinter

# Імпортуємо модулі simpledialog і messagebox для діалогових вікон
from tkinter import simpledialog, messagebox


# Створюємо головне вікно програми
window = tkinter.Tk()

# Встановлюємо заголовок вікна
window.title("Введення даних")  

# Встановлюємо розмір вікна (ширина x висота)
window.geometry("300x150")  


# Створюємо змінну типу StringVar для збереження тексту з поля введення
s = tkinter.StringVar()

# Створюємо порожній список для збереження введених чисел
x = []


# Описуємо функцію, яка виконається при натисканні кнопки
def button_click():
    try:
        # Отримуємо текст з поля вводу та перетворюємо його в ціле число
        n = int(s.get())  # кількість елементів
        
        # Очищаємо список від попередніх значень
        x.clear()  

        # Запускаємо цикл для введення n чисел
        for _ in range(n):
            # Відкриваємо діалогове вікно для введення цілого числа
            num = simpledialog.askinteger("Введення", "Введіть число:")
            
            # Перевіряємо, чи користувач не натиснув кнопку "Скасувати"
            if num is not None:
                # Додаємо введене число до списку
                x.append(num)

        # Виводимо повідомлення з усіма введеними числами
        messagebox.showinfo("Результат", f"Введені числа: {x}")

    # Обробляємо помилку, якщо введено не число
    except ValueError:
        # Виводимо повідомлення про помилку
        messagebox.showerror("Помилка", "Будь ласка, введіть число!")


# Створюємо текстовий напис у вікні
label = tkinter.Label(window, text='Введіть кількість елементів:')

# Розміщуємо напис у вікні
label.pack()

# Створюємо поле для введення тексту
edit = tkinter.Entry(window, textvariable=s)

# Розміщуємо поле вводу у вікні
edit.pack()

# Створюємо кнопку та прив’язуємо до неї функцію button_click
button = tkinter.Button(window, text='Розпочати введення', command=button_click)

# Розміщуємо кнопку у вікні
button.pack()

# Запускаємо головний цикл обробки подій (вікно працює, поки його не закриють)
window.mainloop()